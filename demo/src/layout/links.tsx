export const REPO = "https://github.com/lokendra-builds/sheenui";

/** GitHub link for a path in the repo: files open as blobs, folders as trees. */
export function sourceUrl(path: string) {
  const clean = path.replace(/^\/+|\/+$/g, "");
  const isFile = /\.[a-z0-9]+$/i.test(clean);
  return `${REPO}/${isFile ? "blob" : "tree"}/main/${clean}`;
}

