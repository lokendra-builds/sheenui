// Renames docs routes in one command: `node scripts/rename-routes.mjs [--map scripts/rename-map.json] [--root <repo>] [--dry] [--no-registry]`.
//
// For every old → new pair in the map it
//   1. rewrites the path in demo/src (routes.ts, the keyword map in seo/meta.ts, guides.ts, related links, pages),
//      demo/e2e, demo/scripts, the guides in docs/guides (absolute site URLs and relatedRoutes) and the README;
//   2. writes a client-side redirect stub for the old URL to demo/public/<old>.html (GitHub Pages cannot send a 301):
//      a page with <meta http-equiv="refresh">, a canonical pointing at the new URL and a script that keeps the
//      query string and the hash. Google treats a zero-second refresh as a redirect and follows the canonical;
//   3. regenerates the registry (docs URLs in registry.json and demo/public/r/*.json) unless --no-registry.
// The sitemap, llms.txt and OG cards are generated by the build from routes.ts, so they follow by themselves.
//
// A path is rewritten only where it stands alone: inside quotes ("/charts/pie", `/charts/pie`), in a comma list, after the
// site URL (https://…/sheenui/charts/pie) or after href( , never inside a longer path such as /charts/pie-chart.
// It refuses to run when a new path already exists, or when two pairs collide.
//
// Test it on a copy first (`--root`), then run it on the repo, then `pnpm --filter demo build && pnpm --filter demo seo:check`.

import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { readSplitSource } from "../demo/scripts/lib/split-source.mjs";
import { isAppleDouble } from "./lib/fs-filter.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const flag = (name) => args.includes(name);
const option = (name, fallback) => (args.includes(name) ? args[args.indexOf(name) + 1] : fallback);

const root = resolve(option("--root", resolve(here, "..")));
const mapFile = resolve(option("--map", join(here, "rename-map.json")));
const dry = flag("--dry");

const raw = JSON.parse(readFileSync(mapFile, "utf8"));
/** @type {[string, string][]} */
const pairs = Object.entries(raw).flatMap(([key, value]) =>
  key.startsWith("_") || typeof value !== "object" ? [] : Object.entries(value),
);
if (pairs.length === 0) throw new Error(`rename-routes: no pairs in ${mapFile}`);

const site = readFileSync(join(root, "demo/src/seo/site.ts"), "utf8");
const SITE_URL = /export const SITE_URL = "([^"]+)"/.exec(site)?.[1];
const BASE_PATH = /export const BASE_PATH = "([^"]+)"/.exec(site)?.[1];
if (!SITE_URL || !BASE_PATH)
  throw new Error("rename-routes: cannot read SITE_URL and BASE_PATH from demo/src/seo/site.ts");
const BASE = BASE_PATH.replace(/\/$/, "");

/* ---------- Checks ---------- */

const routesSource = readSplitSource(join(root, "demo/src/routes.ts"));
const existing = new Set([...routesSource.matchAll(/path:\s*"([^"]+)"/g)].map((m) => m[1]));
const problems = [];
const seenNew = new Set();
for (const [from, to] of pairs) {
  if (!existing.has(from)) problems.push(`${from} is not a route (already renamed?)`);
  if (existing.has(to) && !pairs.some(([f]) => f === to)) problems.push(`${to} already exists`);
  if (seenNew.has(to)) problems.push(`${to} is the target of two renames`);
  seenNew.add(to);
}
if (problems.length) {
  console.error(`rename-routes: nothing changed.\n  ${problems.join("\n  ")}`);
  process.exit(1);
}

/* ---------- Which files ---------- */

const SKIP_DIRS = new Set([
  "node_modules",
  ".git",
  "dist",
  "dist-ssr",
  "dist-mine",
  "dist-ssr-mine",
  "playwright-report",
  "test-results",
  "r",
  "public",
]);
function walk(dir, extensions, out = []) {
  if (!existsSync(dir)) return out;
  for (const name of readdirSync(dir)) {
    if (SKIP_DIRS.has(name) || isAppleDouble(name)) continue;
    const file = join(dir, name);
    if (statSync(file).isDirectory()) walk(file, extensions, out);
    else if (extensions.some((e) => name.endsWith(e))) out.push(file);
  }
  return out;
}
const files = [
  ...walk(join(root, "demo/src"), [".ts", ".tsx"]),
  ...walk(join(root, "demo/e2e"), [".ts"]),
  ...walk(join(root, "demo/scripts"), [".mjs"]),
  ...walk(join(root, "docs"), [".md"]),
  join(root, "README.md"),
].filter(existsSync);

/* ---------- Rewrite ---------- */

const escape = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
// Longest paths first, so /charts/radial-bar is never half-matched by /charts/radial.
const ordered = [...pairs].sort((a, b) => b[0].length - a[0].length);
// A path standing alone: after a quote, "href(", a comma (lists) or the site URL, and not followed by a word character or "-".
const patterns = ordered.map(([from, to]) => [
  new RegExp(`(["'\`]|href\\(|,\\s?|${escape(SITE_URL)})${escape(from)}(?![\\w-])`, "g"),
  `$1${to}`,
]);

let changedFiles = 0;
let replacements = 0;
const perFile = [];
for (const file of files) {
  const before = readFileSync(file, "utf8");
  let after = before;
  for (const [re, replacement] of patterns)
    after = after.replace(re, (...m) => (replacements++, replacement.replace("$1", m[1])));
  if (after !== before) {
    changedFiles++;
    perFile.push(relative(root, file));
    if (!dry) writeFileSync(file, after);
  }
}

/* ---------- Redirect stubs ---------- */

const stub = (to) => {
  const target = `${BASE}${to}`;
  return `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>This page moved | SheenUI</title>
    <link rel="canonical" href="${SITE_URL}${to}" />
    <meta http-equiv="refresh" content="0; url=${target}" />
    <script>location.replace(${JSON.stringify(target)} + location.search + location.hash);</script>
  </head>
  <body>
    <p>This page moved to <a href="${target}">${SITE_URL}${to}</a>.</p>
  </body>
</html>
`;
};
const stubs = [];
for (const [from, to] of pairs) {
  const file = join(root, "demo/public", `${from.slice(1)}.html`);
  stubs.push(relative(root, file));
  if (!dry) {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, stub(to));
  }
}

/* ---------- Registry ---------- */

let registry = "skipped";
if (!dry && !flag("--no-registry")) {
  const run = spawnSync(process.execPath, [join(root, "scripts/build-registry.mjs"), "--quiet"], {
    cwd: root,
    encoding: "utf8",
  });
  registry = run.status === 0 ? "regenerated" : `failed (${(run.stderr || run.stdout).trim().split("\n").pop()})`;
}

console.log(
  `${dry ? "[dry run] " : ""}rename-routes: ${pairs.length} routes, ${replacements} replacements in ${changedFiles} files, ${stubs.length} redirect stubs, registry ${registry}.\n` +
    `  files: ${perFile.join(", ")}\n  stubs: ${stubs.join(", ")}\n` +
    `Next: pnpm --filter demo build && pnpm --filter demo seo:check (and run the e2e tests).`,
);
